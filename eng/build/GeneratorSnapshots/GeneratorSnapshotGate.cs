namespace Qyl.Build.GeneratorSnapshots;

/// <summary>
/// Builds the snapshot fixture and compares what the generator emitted byte for byte with the verified
/// snapshots (the interceptors and QylConsumerBuild, the fixture's version and revision as constants);
/// rebuilds every implemented-signal demo to compare live interceptor manifests with the verified artifact. A
/// mismatch leaves the received file beside the generated output. Negative diagnostic behavior is
/// exercised through the actual generator by the native MSTest cases.
/// </summary>
static class GeneratorSnapshotGate
{
    private static AbsolutePath FixtureProject => Repo.Root / "tests" / "Qyl.Telemetry.AutoInstrumentation.SourceGenerators.Snapshots" / "Fixture" / "Qyl.Telemetry.AutoInstrumentation.SourceGenerators.Snapshots.Fixture.csproj";
    private static AbsolutePath GeneratedRoot => Repo.Artifacts / "obj" / FixtureProject.NameWithoutExtension / "generated";
    private static AbsolutePath VerifiedRoot => FixtureProject.Parent.Parent / "verified";
    private static AbsolutePath VerifiedManifestArtifact => VerifiedRoot / "QylAutoInstrumentation.ContractManifests.verified.jsonl";
    private static AbsolutePath ReceivedManifestArtifact => GeneratedRoot / "QylAutoInstrumentation.ContractManifests.received.jsonl";

    private static readonly (string Verified, string Generated)[] ExpectedFiles =
    [
        ("QylAutoInstrumentation.Interceptors.g.verified.cs", "QylAutoInstrumentation.Interceptors.g.cs"),
        ("QylConsumerBuild.g.verified.cs", "QylConsumerBuild.g.cs"),
    ];

    private static readonly string[] RequiredInterceptorTokens =
    [
        "// <auto-generated/>",
        "#nullable enable",
        "file sealed class InterceptsLocationAttribute",
        "namespace Qyl.Telemetry.AutoInstrumentation.Generated",
        "internal static class QylGeneratedInterceptors",
        "// Intercepted call at /_qyl_generator_snapshot/Program.cs",
        "[global::System.Runtime.CompilerServices.InterceptsLocationAttribute(",
        "DbCommand_ExecuteScalar_",
        "global::SnapshotCommand receiver",
        "global::Qyl.Telemetry.AutoInstrumentation.GeneratedCode.QylInterceptedDbCommand.Execute(",
    ];

    private static readonly string[] ForbiddenInterceptorTokens = ["System.Reflection", "Assembly.Load", "Activator.CreateInstance", "QylActivitySource", ".SetTag("];

    public static void Verify()
    {
        RunBuild();
        CompareSnapshots(GeneratedFilesByName());
        CompareContractManifestCoverage();
        Log.Information("generator-snapshots-ok");
    }

    private static void RunBuild()
    {
        GeneratedRoot.DeleteDirectory();
        var result = Shell.Run("dotnet",
        [
            "build", FixtureProject, "-c", "Release", "--disable-build-servers", "--no-incremental", "-maxcpucount:4", "-nodeReuse:false",
            "-v", "normal", "-nologo", "-p:NuGetAudit=false", "-p:UseSharedCompilation=false",
        ], Repo.Root);
        Gate.Require(result.ExitCode == 0, () => "generator snapshot fixture build failed\n" + result.Describe());
    }

    private static Dictionary<string, AbsolutePath> GeneratedFilesByName()
    {
        Gate.Require(GeneratedRoot.DirectoryExists(), $"missing generated output directory: {GeneratedRoot}");
        var files = new Dictionary<string, AbsolutePath>(StringComparer.Ordinal);
        foreach (var path in GeneratedRoot.GlobFiles("**/*.g.cs"))
        {
            if (path.ToString().Split(Path.DirectorySeparatorChar).Contains(GeneratorManifests.GeneratorOutputSegment, StringComparer.Ordinal))
                files[path.Name] = path;
        }

        return files;
    }

    private static void CompareSnapshots(Dictionary<string, AbsolutePath> files)
    {
        var expected = ExpectedFiles.Select(static pair => pair.Generated).ToHashSet(StringComparer.Ordinal);
        var actual = files.Keys.ToHashSet(StringComparer.Ordinal);
        var missing = expected.Except(actual).ToArray();
        var unexpected = actual.Except(expected).ToArray();
        Gate.Require(missing.Length == 0, () => $"missing generated snapshot files: {ContractValue.RenderSorted(missing)}");
        Gate.Require(unexpected.Length == 0, () => $"unexpected generated snapshot files: {ContractValue.RenderSorted(unexpected)}");

        foreach (var (verifiedName, generatedName) in ExpectedFiles)
        {
            var verified = VerifiedRoot / verifiedName;
            var generated = files[generatedName];
            Gate.Require(verified.FileExists(), $"missing verified snapshot: {verified}");
            if (!File.ReadAllBytes(verified).SequenceEqual(File.ReadAllBytes(generated)))
            {
                var received = GeneratedRoot / verifiedName.Replace(".verified.cs", ".received.cs", StringComparison.Ordinal);
                File.Copy(generated, received, overwrite: true);
                throw Gate.Fail($"generator snapshot mismatch\nverified={verified}\nreceived={received}");
            }
        }

        var snapshot = File.ReadAllText(VerifiedRoot / "QylAutoInstrumentation.Interceptors.g.verified.cs");
        foreach (var token in RequiredInterceptorTokens)
            Gate.Require(snapshot.Contains(token, StringComparison.Ordinal), $"interceptor snapshot missing token: {token}");
        foreach (var token in ForbiddenInterceptorTokens)
            Gate.Require(!snapshot.Contains(token, StringComparison.Ordinal), $"interceptor snapshot must not inline runtime telemetry behavior: {token}");
    }

    private static void CompareContractManifestCoverage()
    {
        Gate.Require(VerifiedManifestArtifact.FileExists(), $"missing verified generator manifest artifact: {VerifiedManifestArtifact}");
        var received = GeneratorManifests.CollectLiveManifestArtifact();
        if (received == File.ReadAllText(VerifiedManifestArtifact))
            return;

        ReceivedManifestArtifact.Parent.CreateDirectory();
        File.WriteAllText(ReceivedManifestArtifact, received);
        throw Gate.Fail($"generator contract manifest snapshot mismatch\nverified={VerifiedManifestArtifact}\nreceived={ReceivedManifestArtifact}");
    }
}
